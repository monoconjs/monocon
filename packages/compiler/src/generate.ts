import { mkdir, writeFile } from 'node:fs/promises'
import { relative, resolve } from 'node:path'

import type { Declaration, RouteDecl, ErrorDecl, MiddlewareDecl } from './analyze.ts'
import { analyzeEntries } from './analyze.ts'
import { expandEntries, loadConfig } from './config.ts'
import { matchMiddlewares } from './match.ts'

export interface GeneratedFile {
  readonly path: string
  readonly content: string
}

export interface GenerateResult {
  readonly files: GeneratedFile[]
  readonly declarations: Declaration[]
  readonly warnings: string[]
}

export async function generate(cwd: string, configFile: string): Promise<GenerateResult> {
  const config = await loadConfig(resolve(cwd, configFile))
  const entryFiles = await expandEntries(config.entry)
  const { declarations, warnings } = await analyzeEntries(entryFiles)

  const outputDir = resolve(cwd, '.monocon')
  const routes = declarations.filter((item): item is RouteDecl => item.kind === 'route')
  const middlewares = declarations.filter(
    (item): item is MiddlewareDecl => item.kind === 'middleware',
  )
  const errors = declarations.filter((item): item is ErrorDecl => item.kind === 'error')

  const types = renderTypes(outputDir, routes, middlewares, errors)
  const registry = renderRegistry(outputDir, declarations)
  const registryTypes = renderRegistryTypes(outputDir, declarations)

  await mkdir(outputDir, { recursive: true })
  await writeFile(resolve(outputDir, 'types.d.ts'), types)
  await writeFile(resolve(outputDir, 'registry.mjs'), registry)
  await writeFile(resolve(outputDir, 'registry.d.mts'), registryTypes)

  return {
    files: [
      { path: resolve(outputDir, 'types.d.ts'), content: types },
      { path: resolve(outputDir, 'registry.mjs'), content: registry },
      { path: resolve(outputDir, 'registry.d.mts'), content: registryTypes },
    ],
    declarations,
    warnings,
  }
}

function renderTypes(
  outputDir: string,
  routes: RouteDecl[],
  middlewares: MiddlewareDecl[],
  errors: ErrorDecl[],
): string {
  const rows: Array<{ method: string; path: string; matched: MiddlewareDecl[] }> = []
  const seenKeys = new Set<string>()

  for (const route of routes) {
    const key = `${route.method} ${route.path}`
    if (seenKeys.has(key)) continue
    seenKeys.add(key)

    const matched = matchMiddlewares(middlewares, route.path, route.method)
    if (matched.length > 0) rows.push({ method: route.method, path: route.path, matched })
  }

  const imports = collectImports(
    outputDir,
    rows.flatMap((row) => row.matched),
    errors,
  )

  const recordRoutes = routes.filter((route) => route.method !== 'ALL' && !route.path.includes('*'))
  const routeImports = collectRouteImports(outputDir, recordRoutes)
  const routeRecords = renderRouteRecords(recordRoutes, routeImports.ref)

  const lines = [
    '// Generated by monocon. Do not edit.',
    '/* eslint-disable */',
    '/* oxlint-disable */',
    '/* prettier-ignore */',
    '',
    ...imports,
    ...routeImports.lines,
    '',
    "declare module 'monocon/global' {",
    '  interface RouteMiddlewareContext {',
  ]

  for (const row of rows) {
    const provided = row.matched
      .map((middleware) => `(typeof ${middleware.exportName})['~provided']`)
      .join(' & ')
    lines.push(`    ${JSON.stringify(`${row.method} ${row.path}`)}: ${provided}`)
  }

  lines.push('  }')
  lines.push('')
  lines.push('  interface ErrorMap {')
  for (const item of errors) {
    const key = item.name ?? item.exportName
    lines.push(`    ${JSON.stringify(key)}: (typeof ${item.exportName})['~payload']`)
  }
  lines.push('  }')
  lines.push('')
  lines.push('  interface ErrorStatusMap {')
  for (const item of errors) {
    const key = item.name ?? item.exportName
    lines.push(`    ${JSON.stringify(key)}: (typeof ${item.exportName})['~status']`)
  }
  lines.push('  }')
  lines.push('')
  lines.push(...routeRecords)
  lines.push('}', '')
  return lines.join('\n')
}

interface RouteImports {
  readonly lines: string[]
  readonly ref: (route: RouteDecl) => string
}

function collectRouteImports(outputDir: string, routes: RouteDecl[]): RouteImports {
  const aliases = new Map<string, string>()
  const refs = new Map<RouteDecl, string>()
  const lines: string[] = []
  let index = 0

  for (const route of routes) {
    let alias = aliases.get(route.file)
    if (!alias) {
      alias = `__routes_${index++}`
      aliases.set(route.file, alias)
      lines.push(`import * as ${alias} from '${importSpecifier(outputDir, route.file)}'`)
    }
    refs.set(route, `${alias}.${route.exportName}`)
  }

  return { lines, ref: (route) => refs.get(route) ?? route.exportName }
}

function renderRouteRecords(routes: RouteDecl[], ref: (route: RouteDecl) => string): string[] {
  const groups = new Map<string, Map<string, string>>()

  for (const route of routes) {
    const method = route.method.toLowerCase()
    let methods = groups.get(route.path)
    if (!methods) {
      methods = new Map()
      groups.set(route.path, methods)
    }
    methods.set(method, `      ${method}: typeof ${ref(route)}`)
  }

  const lines = ['  interface RouteRecords {']
  for (const [path, methods] of groups) {
    lines.push(`    ${JSON.stringify(path)}: {`)
    for (const method of methods.values()) lines.push(method)
    lines.push('    }')
  }
  lines.push('  }')
  return lines
}

function collectImports(
  outputDir: string,
  middlewares: MiddlewareDecl[],
  errors: ErrorDecl[],
): string[] {
  const groups = new Map<string, string[]>()

  for (const item of [...middlewares, ...errors]) {
    const specifier = importSpecifier(outputDir, item.file)
    const names = groups.get(specifier) ?? []
    if (!names.includes(item.exportName)) names.push(item.exportName)
    groups.set(specifier, names)
  }

  const lines: string[] = ["import 'monocon/global'"]
  for (const [specifier, names] of groups) {
    lines.push(`import { ${names.join(', ')} } from '${specifier}'`)
  }
  return lines
}

function renderRegistry(outputDir: string, declarations: Declaration[]): string {
  const files = [...new Set(declarations.map((declaration) => declaration.file))]

  const lines = [
    '// Generated by monocon. Do not edit.',
    '/* eslint-disable */',
    '/* oxlint-disable */',
    '/* prettier-ignore */',
    '',
  ]

  for (const file of files) {
    lines.push(`export * from '${importSpecifier(outputDir, file)}'`)
  }

  lines.push('')
  return lines.join('\n')
}

function renderRegistryTypes(outputDir: string, declarations: Declaration[]): string {
  const files = [...new Set(declarations.map((declaration) => declaration.file))]

  const lines = [
    '// Generated by monocon. Do not edit.',
    '/* eslint-disable */',
    '/* oxlint-disable */',
    '/* prettier-ignore */',
    '',
  ]

  for (const file of files) {
    lines.push(`export * from '${importSpecifier(outputDir, file)}'`)
  }

  lines.push('')
  return lines.join('\n')
}

function importSpecifier(outputDir: string, file: string): string {
  const path = relative(outputDir, file).split('\\').join('/')
  const specifier = path.startsWith('.') ? path : `./${path}`
  return specifier.replace(/\.(ts|mts|cts|tsx)$/, '.js')
}
