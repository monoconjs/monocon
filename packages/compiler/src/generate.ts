import { mkdir, writeFile } from 'node:fs/promises'
import { relative, resolve } from 'node:path'

import type { Declaration, RouteDecl, ErrorDecl, MiddlewareDecl } from './analyze.ts'
import { analyzeEntries, readOrderedNames } from './analyze.ts'
import { expandEntries, loadConfig } from './config.ts'
import { matchMiddlewares } from './match.ts'

export interface GeneratedFile {
  readonly path: string
  readonly content: string
}

export interface GenerateResult {
  readonly files: GeneratedFile[]
  readonly declarations: Declaration[]
  readonly warnings: string[]
}

const GENERATED_HEADER = [
  '// Generated by monocon. Do not edit.',
  '/* eslint-disable */',
  '/* oxlint-disable */',
  '/* prettier-ignore */',
  '',
]

function orderByNames<T extends Declaration>(declarations: T[], names: string[]): T[] {
  const byName = new Map(declarations.map((item) => [item.exportName, item]))
  const ordered: T[] = []
  const used = new Set<string>()
  for (const name of names) {
    const item = byName.get(name)
    if (item && !used.has(name)) {
      ordered.push(item)
      used.add(name)
    }
  }
  for (const item of declarations) {
    if (!used.has(item.exportName)) ordered.push(item)
  }
  return ordered
}

async function collectOrderedNames(files: string[]): Promise<string[]> {
  const groups = await Promise.all(files.map((file) => readOrderedNames(file).catch(() => [])))
  return [...new Set(groups.flat())]
}

export async function generate(cwd: string, configFile: string): Promise<GenerateResult> {
  const config = await loadConfig(resolve(cwd, configFile))
  const entryFiles = await expandEntries(config.entry)
  const { declarations: scanned, warnings } = await analyzeEntries(entryFiles)

  // Any scanned file may export an ordered declaration array. Its order wins
  // over the order in which the files were discovered.
  const orderedNames = await collectOrderedNames(entryFiles)

  const routes = orderByNames(
    scanned.filter((item): item is RouteDecl => item.kind === 'route'),
    orderedNames,
  )
  const middlewares = orderByNames(
    scanned.filter((item): item is MiddlewareDecl => item.kind === 'middleware'),
    orderedNames,
  )
  const errors = scanned.filter((item): item is ErrorDecl => item.kind === 'error')

  const declarations: Declaration[] = [...routes, ...middlewares, ...errors]
  const outputDir = resolve(cwd, '.monocon')
  const files = renderDeclarations(outputDir, routes, middlewares, errors)

  await mkdir(outputDir, { recursive: true })
  await Promise.all(files.map((file) => writeFile(file.path, file.content)))

  return { files, declarations, warnings }
}

interface ContextRow {
  readonly method: string
  readonly path: string
  readonly matched: MiddlewareDecl[]
}

function renderDeclarations(
  outputDir: string,
  routes: RouteDecl[],
  middlewares: MiddlewareDecl[],
  errors: ErrorDecl[],
): GeneratedFile[] {
  const rows: ContextRow[] = []
  const seenKeys = new Set<string>()

  for (const route of routes) {
    const key = `${route.method} ${route.path}`
    if (seenKeys.has(key)) continue
    seenKeys.add(key)

    // matchMiddlewares preserves the input (array) order.
    const matched = matchMiddlewares(middlewares, route.path, route.method)
    if (matched.length > 0) rows.push({ method: route.method, path: route.path, matched })
  }

  const contextImports = collectImports(
    outputDir,
    rows.flatMap((row) => row.matched),
    [],
  )
  const errorImports = collectImports(outputDir, [], errors)

  const recordRoutes = routes.filter((route) => route.method !== 'ALL' && !route.path.includes('*'))
  const routeImports = collectRouteImports(outputDir, recordRoutes)
  const routeRecords = renderRouteRecords(recordRoutes, routeImports.ref)

  const contextBody = [
    '  interface RouteMiddlewareContext {',
    ...rows.map((row) => {
      const provided = row.matched
        .map((middleware) => `(typeof ${middleware.exportName})['~provided']`)
        .join(' & ')
      return `    ${JSON.stringify(`${row.method} ${row.path}`)}: ${provided}`
    }),
    '  }',
  ]

  const errorBody = [
    '  interface ErrorMap {',
    ...errors.map((item) => {
      const key = item.name ?? item.exportName
      return `    ${JSON.stringify(key)}: (typeof ${item.exportName})['~payload']`
    }),
    '  }',
    '',
    '  interface ErrorStatusMap {',
    ...errors.map((item) => {
      const key = item.name ?? item.exportName
      return `    ${JSON.stringify(key)}: (typeof ${item.exportName})['~status']`
    }),
    '  }',
  ]

  const types = [
    ...GENERATED_HEADER,
    "import './middlewares.js'",
    "import './errors.js'",
    "import './routes.js'",
    '',
  ].join('\n')

  return [
    { path: resolve(outputDir, 'types.d.ts'), content: types },
    {
      path: resolve(outputDir, 'middlewares.d.ts'),
      content: renderAugmentation(contextImports, contextBody),
    },
    {
      path: resolve(outputDir, 'errors.d.ts'),
      content: renderAugmentation(errorImports, errorBody),
    },
    {
      path: resolve(outputDir, 'routes.d.ts'),
      content: renderAugmentation(["import 'monocon/global'", ...routeImports.lines], routeRecords),
    },
  ]
}

function renderAugmentation(imports: string[], body: string[]): string {
  return [
    ...GENERATED_HEADER,
    ...imports,
    '',
    "declare module 'monocon/global' {",
    ...body,
    '}',
    '',
  ].join('\n')
}

interface RouteImports {
  readonly lines: string[]
  readonly ref: (route: RouteDecl) => string
}

function collectRouteImports(outputDir: string, routes: RouteDecl[]): RouteImports {
  const aliases = new Map<string, string>()
  const refs = new Map<RouteDecl, string>()
  const lines: string[] = []
  let index = 0

  for (const route of routes) {
    let alias = aliases.get(route.file)
    if (!alias) {
      alias = `__routes_${index++}`
      aliases.set(route.file, alias)
      lines.push(`import * as ${alias} from '${importSpecifier(outputDir, route.file)}'`)
    }
    refs.set(route, `${alias}.${route.default ? 'default' : route.exportName}`)
  }

  return { lines, ref: (route) => refs.get(route) ?? route.exportName }
}

function renderRouteRecords(routes: RouteDecl[], ref: (route: RouteDecl) => string): string[] {
  const groups = new Map<string, Map<string, string>>()

  for (const route of routes) {
    const method = route.method.toLowerCase()
    let methods = groups.get(route.path)
    if (!methods) {
      methods = new Map()
      groups.set(route.path, methods)
    }
    methods.set(method, `      ${method}: typeof ${ref(route)}`)
  }

  const lines = ['  interface RouteRecords {']
  for (const [path, methods] of groups) {
    lines.push(`    ${JSON.stringify(path)}: {`)
    for (const method of methods.values()) lines.push(method)
    lines.push('    }')
  }
  lines.push('  }')
  return lines
}

function collectImports(
  outputDir: string,
  middlewares: MiddlewareDecl[],
  errors: ErrorDecl[],
): string[] {
  const groups = new Map<string, string[]>()

  for (const item of [...middlewares, ...errors]) {
    const specifier = importSpecifier(outputDir, item.file)
    const names = groups.get(specifier) ?? []
    const importName = item.default ? `default as ${item.exportName}` : item.exportName
    if (!names.includes(importName)) names.push(importName)
    groups.set(specifier, names)
  }

  const lines = ["import 'monocon/global'"]
  for (const [specifier, names] of groups) {
    lines.push(`import { ${names.join(', ')} } from '${specifier}'`)
  }
  return lines
}

function importSpecifier(outputDir: string, file: string): string {
  const path = relative(outputDir, file).split('\\').join('/')
  const specifier = path.startsWith('.') ? path : `./${path}`
  return specifier.replace(/\.(ts|mts|cts|tsx)$/, '.js')
}
